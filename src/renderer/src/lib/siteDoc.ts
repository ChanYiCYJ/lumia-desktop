/**
 * 判断用户消息是否在询问"本站操作/使用/功能"。
 * 命中才注入操作文档（token 优化）；"怎么用 React 写代码"这类与本站无关的提问不命中。
 */
export function isSiteDocQuery(userMsg: string): boolean {
  const t = (userMsg || "").trim();
  if (!t) return false;
  // ① 明确指向"本站/这个站" + 询问怎么用/操作/功能
  if (
    /本站|这个站|这个网站|这个站点|本站点/.test(t) &&
    /怎么|如何|怎样|能|可以|用|操作|使用|设置|配置|发布|管理|功能|介绍|文档|帮助/.test(
      t,
    )
  )
    return true;
  // ② 直接提"文档 / 操作说明 / 功能说明"
  if (
    /使用文档|操作文档|操作手册|帮助文档|使用说明|操作说明|站点功能|功能说明|有哪些功能|使用指南|操作指南/.test(
      t,
    )
  )
    return true;
  // ③ 本站独有功能 + 疑问/操作意图（自定义模型/Live2D/换角色/数据管理/网络模式等基本只在本站出现，无需"本站"锚定）
  if (
    /自定义模型|自定义api|自定义接口|live2d|换角色|切换角色|自动随机|网络模式|搜索模式|角色设定|数据管理/.test(
      t,
    ) &&
    /怎么|如何|怎样|能|可以|在哪|哪里|用|操作|使用|设置|配置|开启|关闭|导入|导出|保存|删除/.test(
      t,
    )
  )
    return true;
  // ④ 较通用的本站功能 + "本站/这个站" 锚定
  if (
    /本站|这个站|这个网站|站点/.test(t) &&
    /发文章|发布|写文章|投稿|登录|注册|后台|管理|知识库|导出|导入|换主题|深色|暗色|字体|会话|记忆/.test(
      t,
    )
  )
    return true;
  return false;
}

/**
 * 判断用户消息是否在要求「综合多源资料」（本地知识库 🧠 + 网络结果 🌐 等）作答。
 * 命中才注入【知识融合】指令段（token 优化）；"综合国力/结合实际情况/总结怎么写代码"
 * 等日常词不命中（保守正则，避免误触发）。
 */
export function isKnowledgeFusionQuery(userMsg: string): boolean {
  const t = (userMsg || "").trim();
  if (!t) return false;
  // ① 融合动词 + 明确的多源/知识库锚定（结合知识库(和网络/搜索)…、综合本地知识与网络…）
  if (
    /(结合|综合|融合|汇总|对比|比较)/.test(t) &&
    /知识库|本地知识|已有知识|以上资料|这些资料|多(个|方)?来源/.test(t)
  )
    return true;
  // ② 融合/归纳动词 + 资料范围锚定（资料/信息/来源/这些/以上 等）
  if (
    /(结合|综合|融合|汇总|总结|归纳|整合|对比|比较|综合分析|梳理)/.test(t) &&
    /(资料|信息|知识|结果|内容|来源|方面|角度|这些|以上|两边|两者|双方|各个|多(方面|角度|来源))/.test(
      t,
    )
  )
    return true;
  // ③ 明确的多源指向 + 综合意图（根据以上…/基于这些…）
  if (
    /(根据|基于|综合)(以上|这些|上述|全部)/.test(t) &&
    /(资料|信息|内容|结果|来源|回答|总结|整理|对比|归纳)/.test(t)
  )
    return true;
  return false;
}
